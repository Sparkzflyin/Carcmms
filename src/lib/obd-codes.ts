const PATTERN = /^[PBCU][0-3][0-9A-F]{3}$/;

export function normalizeCode(raw: string) {
  return raw
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");
}

export function isValidCode(code: string) {
  return PATTERN.test(code);
}

export function lookupCode(raw: string): CodeInfo | null {
  const code = normalizeCode(raw);
  if (!isValidCode(code)) return null;
  const letter = code[0];
  const digit = code[1];
  // SAE-defined: P0, P2, P34–P39, and B0/C0/U0 plus B3/C3/U3. The rest are
  // manufacturer-defined.
  const generic =
    digit === "0" ||
    (letter === "P" && (digit === "2" || (digit === "3" && code[2] >= "4"))) ||
    (letter !== "P" && digit === "3");
  return {
    code,
    description: CODES[code] ?? null,
    system: SYSTEMS[letter],
    generic,
    // The third-character breakdown applies to P0/P1/P2; P3 is laid out differently.
    subsystem: letter === "P" && digit !== "3" ? (P_SUBSYSTEMS[code[2]] ?? null) : null,
    causes: CAUSES[code],
  };
}

